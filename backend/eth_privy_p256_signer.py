"""Privy additional-signer P-256 authorization of an exact ETH wallet RPC POST.

RFC 8785/JCS JSON formatting for the restricted ASCII-only request shape
generated by MiniNex: all strings and integer version, no floats or Unicode.
No key generation, no key export, no signing endpoint. Key loaded from the
server's existing/explicit Privy P-256 authorization secret at execution time.
"""
from __future__ import annotations

import base64
import binascii
import json
import os
import re

from cryptography.hazmat.primitives import hashes,serialization
from cryptography.hazmat.primitives.asymmetric import ec
from fastapi import HTTPException

from .privy_wallet_verification import APP_ID
from .eth_privy_auto_transport import bound_privy_rpc_request

_KEY_ENV="MININEX_PRIVY_ETH_AUTH_P256_PKCS8"
_KEY_ID=re.compile(r"^[A-Za-z0-9_-]{16,96}$")


def _canonical_authorization_payload(*,url:str,body:dict,key:str) -> bytes:
    if (type(url) is not str
            or not url.startswith("https://api.privy.io/v1/wallets/")
            or not url.endswith("/rpc")
            or type(body) is not dict
            or type(key) is not str or not _KEY_ID.fullmatch(key)):
        raise ValueError("Invalid Privy request signing context")
    request={
        "version":1,"method":"POST","url":url,
        "body":body,
        "headers":{
            "privy-app-id":APP_ID,
            "privy-idempotency-key":key,
        },
    }
    raw=json.dumps(request,sort_keys=True,separators=(",",":"),
                   ensure_ascii=False,allow_nan=False).encode("utf-8")
    # All actual fields are strict ASCII and contain no JS-specific number
    # formatting; this is the same RFC 8785 byte representation for these
    # bounded fields. If Privy expands body schema, do not silently sign it.
    if not raw.isascii():
        raise ValueError("Non-ASCII Privy authorization payload")
    return raw


def sign_privy_eth_request(*,wallet_id:str,wallet:str,tx:dict,
                           side:str,stable:str,input_atomic:str,
                           minimum_output_atomic:str,
                           idempotency_key:str)->str:
    """Create DER/Base64 ECDSA P-256 signature over SHA-256 of exact body.

    Caller must first commit immutable SENDING order status and verify
    the owner's current delegated signer. The same signing input is used
    by broadcast_privy_eth_swap; no user-supplied signature is accepted.
    """
    url,body=bound_privy_rpc_request(
        wallet_id=wallet_id,wallet=wallet,tx=tx,
        side=side,stable=stable,
        input_atomic=input_atomic,
        minimum_output_atomic=minimum_output_atomic)
    payload=_canonical_authorization_payload(
        url=url,body=body,key=idempotency_key)
    encoded=os.environ.get(_KEY_ENV,"").strip()
    if not encoded or len(encoded)>4096:
        raise HTTPException(503,"Privy additional signer key not configured")
    try:
        der=base64.b64decode(encoded,validate=True)
        private=serialization.load_der_private_key(der,password=None)
        if (not isinstance(private,ec.EllipticCurvePrivateKey)
                or not isinstance(private.curve,ec.SECP256R1)):
            raise ValueError("Wrong signer key curve")
        signature=private.sign(payload,ec.ECDSA(hashes.SHA256()))
        return base64.b64encode(signature).decode("ascii")
    except (ValueError,TypeError,binascii.Error):
        raise HTTPException(503,"Privy additional signer key invalid") from None
